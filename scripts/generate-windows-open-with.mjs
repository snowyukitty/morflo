import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "..");
const manifestPath = resolve(repositoryRoot, "src-tauri", "windows", "open-with.json");
const outputPath = resolve(repositoryRoot, "src-tauri", "windows", "hooks.nsh");
const checkOnly = process.argv.includes("--check");

function assertString(value, label, pattern) {
  if (typeof value !== "string" || !pattern.test(value)) {
    throw new Error(`Invalid ${label} in ${manifestPath}.`);
  }
  return value;
}

function quoteNsis(value) {
  if (value.includes('"') || value.includes("\r") || value.includes("\n")) {
    throw new Error("Open with manifest strings cannot contain quotes or line breaks.");
  }
  return value;
}

function renderHooks(manifest) {
  if (manifest.schemaVersion !== 1) {
    throw new Error(`Unsupported Open with manifest schema: ${manifest.schemaVersion}.`);
  }
  const progId = assertString(manifest.progId, "ProgID", /^[A-Za-z][A-Za-z0-9.]+$/u);
  const applicationName = assertString(
    manifest.applicationName,
    "application name",
    /^[^"\r\n]+$/u,
  );
  const applicationDescription = assertString(
    manifest.applicationDescription,
    "application description",
    /^[^"\r\n]+$/u,
  );
  const fileTypeDescription = assertString(
    manifest.fileTypeDescription,
    "file type description",
    /^[^"\r\n]+$/u,
  );
  const executable = assertString(manifest.executable, "executable", /^[A-Za-z0-9._-]+\.exe$/u);
  if (!Array.isArray(manifest.extensions) || manifest.extensions.length === 0) {
    throw new Error("The Open with manifest needs at least one extension.");
  }
  const extensions = [...new Set(manifest.extensions)].map((extension) =>
    assertString(extension, "file extension", /^[a-z0-9]+$/u),
  );
  if (extensions.length !== manifest.extensions.length) {
    throw new Error("The Open with manifest contains duplicate extensions.");
  }
  const openCommand = String.raw`$\"$INSTDIR\__MORFLO_EXECUTABLE__$\" $\"%1$\"`.replace(
    "__MORFLO_EXECUTABLE__",
    "${MORFLO_EXECUTABLE}",
  );

  const lines = [
    "; Generated by scripts/generate-windows-open-with.mjs. Do not edit directly.",
    "; Morflo registers only as an Open with candidate. It never changes user defaults.",
    "",
    `!define MORFLO_PROGID "${quoteNsis(progId)}"`,
    `!define MORFLO_APP_NAME "${quoteNsis(applicationName)}"`,
    `!define MORFLO_APP_DESCRIPTION "${quoteNsis(applicationDescription)}"`,
    `!define MORFLO_FILE_DESCRIPTION "${quoteNsis(fileTypeDescription)}"`,
    `!define MORFLO_EXECUTABLE "${quoteNsis(executable)}"`,
    "",
    "!macro MORFLO_REGISTER_EXTENSION EXT",
    '  WriteRegStr HKCU "Software\\Classes\\.${EXT}\\OpenWithProgids" "${MORFLO_PROGID}" ""',
    '  WriteRegStr HKCU "Software\\Morflo\\Capabilities\\FileAssociations" ".${EXT}" "${MORFLO_PROGID}"',
    '  WriteRegStr HKCU "Software\\Classes\\Applications\\${MORFLO_EXECUTABLE}\\SupportedTypes" ".${EXT}" ""',
    "!macroend",
    "",
    "!macro MORFLO_UNREGISTER_EXTENSION EXT",
    '  DeleteRegValue HKCU "Software\\Classes\\.${EXT}\\OpenWithProgids" "${MORFLO_PROGID}"',
    '  DeleteRegValue HKCU "Software\\Morflo\\Capabilities\\FileAssociations" ".${EXT}"',
    '  DeleteRegValue HKCU "Software\\Classes\\Applications\\${MORFLO_EXECUTABLE}\\SupportedTypes" ".${EXT}"',
    "!macroend",
    "",
    "!macro NSIS_HOOK_POSTINSTALL",
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}" "" "${MORFLO_FILE_DESCRIPTION}"',
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}" "AllowSilentDefaultTakeOver" ""',
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}\\DefaultIcon" "" "$INSTDIR\\${MORFLO_EXECUTABLE},0"',
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}\\shell" "" "open"',
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}\\shell\\open" "" "Open with ${MORFLO_APP_NAME}"',
    '  WriteRegStr HKCU "Software\\Classes\\${MORFLO_PROGID}\\shell\\open\\command" "" "' +
      openCommand +
      '"',
    '  WriteRegStr HKCU "Software\\Classes\\Applications\\${MORFLO_EXECUTABLE}" "FriendlyAppName" "${MORFLO_APP_NAME}"',
    '  WriteRegStr HKCU "Software\\Classes\\Applications\\${MORFLO_EXECUTABLE}\\shell\\open\\command" "" "' +
      openCommand +
      '"',
    '  WriteRegStr HKCU "Software\\Morflo\\Capabilities" "ApplicationName" "${MORFLO_APP_NAME}"',
    '  WriteRegStr HKCU "Software\\Morflo\\Capabilities" "ApplicationDescription" "${MORFLO_APP_DESCRIPTION}"',
    '  WriteRegStr HKCU "Software\\RegisteredApplications" "${MORFLO_APP_NAME}" "Software\\Morflo\\Capabilities"',
    ...extensions.map((extension) => `  !insertmacro MORFLO_REGISTER_EXTENSION "${extension}"`),
    '  System::Call "shell32::SHChangeNotify(i 0x08000000, i 0x1000, p 0, p 0)"',
    "!macroend",
    "",
    "!macro NSIS_HOOK_PREUNINSTALL",
    ...extensions.map(
      (extension) => `  !insertmacro MORFLO_UNREGISTER_EXTENSION "${extension}"`,
    ),
    '  DeleteRegValue HKCU "Software\\RegisteredApplications" "${MORFLO_APP_NAME}"',
    '  DeleteRegKey HKCU "Software\\Morflo\\Capabilities"',
    '  DeleteRegKey /ifempty HKCU "Software\\Morflo"',
    '  DeleteRegKey HKCU "Software\\Classes\\Applications\\${MORFLO_EXECUTABLE}"',
    '  DeleteRegKey HKCU "Software\\Classes\\${MORFLO_PROGID}"',
    '  System::Call "shell32::SHChangeNotify(i 0x08000000, i 0x1000, p 0, p 0)"',
    "!macroend",
  ];
  return `${lines.join("\n")}\n`;
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const rendered = renderHooks(manifest);
const current = await readFile(outputPath, "utf8").catch(() => undefined);

if (checkOnly) {
  if (current !== rendered) {
    throw new Error(
      `Generated Open with hooks are stale. Run: pnpm generate:windows-open-with`,
    );
  }
  process.stdout.write(
    `Open with hooks are current for ${manifest.extensions.length} extensions.\n`,
  );
} else {
  await writeFile(outputPath, rendered, "utf8");
  process.stdout.write(
    `Generated Open with hooks for ${manifest.extensions.length} extensions.\n`,
  );
}
